/**
 * Adds the local Keycloak / OIDC development settings to the repository-root .env.
 * Only keys that are missing or empty are written; existing values are never changed.
 * Secrets are generated randomly and never printed.
 *
 *   npm run auth:init-env            add missing keys
 *   npm run auth:init-env -- --check exit 1 if any required key is missing (used by keycloak:up)
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const envPath = fileURLToPath(new URL('../../.env', import.meta.url));
const secret = () => randomBytes(32).toString('base64url');

const defaults: Record<string, () => string> = {
  OIDC_ISSUER: () => 'http://localhost:8080/realms/educomply',
  OIDC_CLIENT_ID: () => 'educomply-api',
  OIDC_CLIENT_SECRET: secret,
  OIDC_REDIRECT_URI: () => 'http://localhost:5173/api/v1/auth/oidc/callback',
  KEYCLOAK_ADMIN_USERNAME: () => 'educomply-admin',
  KEYCLOAK_ADMIN_PASSWORD: secret,
};

const text = existsSync(envPath) ? readFileSync(envPath, 'utf8') : '';
const lines = text.split(/\r?\n/);
const valueOf = (key: string) => {
  const line = lines.find((l) => l.startsWith(`${key}=`));
  return (
    line
      ?.slice(key.length + 1)
      .replace(/^"|"$/g, '')
      .trim() ?? ''
  );
};
const missing = Object.keys(defaults).filter((key) => valueOf(key) === '');

if (process.argv.includes('--check')) {
  if (missing.length > 0) {
    console.error(`Missing in .env: ${missing.join(', ')}. Run: npm run auth:init-env`);
    process.exit(1);
  }
  process.exit(0);
}

if (missing.length === 0) {
  console.log('.env already has all Keycloak/OIDC development settings; nothing changed.');
  process.exit(0);
}

const updated = [...lines];
const appended: string[] = [];
for (const key of missing) {
  const index = updated.findIndex((l) => l.startsWith(`${key}=`));
  const line = `${key}=${defaults[key]!()}`;
  if (index >= 0) updated[index] = line;
  else appended.push(line);
}
let output = updated.join('\n').replace(/\n*$/, '\n');
if (appended.length > 0) {
  output += `\n# Keycloak / OIDC (local development, generated by npm run auth:init-env)\n${appended.join('\n')}\n`;
}
writeFileSync(envPath, output, 'utf8');
console.log(`Added to .env (values not shown): ${missing.join(', ')}`);
console.log(
  'If Keycloak was already started with other values, recreate it: npm run keycloak:reset',
);
